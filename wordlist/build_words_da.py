#!/usr/bin/env python3
"""Build words-da.js, the Danish spelling words, from wordlist/da/Y1.txt to Y6.txt.

Usage:  python3 wordlist/build_words_da.py [--no-spell]

Each file is one level: Y1 is 0. klasse (the same age as Year 1) up to Y6, 5. klasse. Each line is
word|meaning|example sentence|why it's tricky (empty when the word is spelled as it sounds); lines starting
with # are notes. The words were written for Typing Zen (2026-10-29), from the most common Danish words up
to harder words with silent letters, soft d, double consonants and loanwords.

It stops and lists any problems: a word twice, a word not in its sentence (whole word, the same form), a
sentence without an end mark, or (on a Mac) a word or sentence word that macOS's Danish dictionary doesn't
know, or a letter that isn't on the Danish keyboard. Names and a few known words are allowed in da/allow.txt.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "words-da.js"
LETTERS = "a-zA-ZæøåÆØÅ"
# Names in example sentences, and correct words the macOS dictionary is missing.
ALLOW = set((HERE / "da" / "allow.txt").read_text(encoding="utf-8").split()) if (HERE / "da" / "allow.txt").exists() else set()


def found(sentence, word):
    return re.search(rf"(?<![{LETTERS}\d_'-]){re.escape(word)}(?![{LETTERS}\d_'-])", sentence, re.I) is not None


def main():
    levels, problems, seen = [], [], {}
    for y in range(1, 7):
        path = HERE / "da" / f"Y{y}.txt"
        words = []
        for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip() or line.startswith("#"):
                continue
            parts = line.split("|")
            where = f"Y{y}.txt:{n}"
            if len(parts) != 4:
                problems.append(f"{where}: needs 4 parts: {line}")
                continue
            word, meaning, sentence, why = (p.strip() for p in parts)
            if not re.fullmatch(rf"[{LETTERS}]+(-[{LETTERS}]+)?", word):
                problems.append(f"{where}: odd word {word!r}")
            if word.lower() in seen:
                problems.append(f"{where}: {word} is also at {seen[word.lower()]}")
                continue
            seen[word.lower()] = where
            if not meaning:
                problems.append(f"{where}: {word} has no meaning")
            if not found(sentence, word):
                problems.append(f"{where}: {word!r} is not in its sentence: {sentence}")
            # Everything must be typable on the Danish keyboard (app.js LAYOUTS.da), so no é or other accents.
            if not re.fullmatch(r"[a-zæøåA-ZÆØÅ0-9 ½§!\"#¤%&/()=?`´^¨*'<>,;.:_+-]*", word + sentence):
                problems.append(f"{where}: a letter that isn't on the Danish keyboard: {word}: {sentence}")
            if not re.search(r"[.!?]$", sentence):
                problems.append(f"{where}: the sentence needs an end mark: {sentence}")
            words.append([word, meaning, sentence, why, where])
        levels.append(words)

    if "--no-spell" not in sys.argv:
        rows = [w for level in levels for w in level]
        text = "\n".join(f"{w[0]} {w[2]}" for w in rows) + "\n"
        out = subprocess.run(["swift", str(HERE / "da" / "spell.swift")], input=text, capture_output=True, text=True)
        if out.returncode:
            sys.exit("spell check failed (use --no-spell to skip it):\n" + out.stderr[-2000:])
        for line in out.stdout.splitlines():
            n, bad = line.split("\t")
            if bad in ALLOW:
                continue
            w = rows[int(n) - 1]
            problems.append(f"{w[4]}: the Danish dictionary doesn't know {bad!r} ({w[0]}: {w[2]})")

    if problems:
        sys.exit("\n".join(problems) + f"\n{len(problems)} problem(s)")
    groups = [{"group": y, "level": f"Y{y}", "words": [w[:4] for w in level]} for y, level in enumerate(levels, 1)]
    lines = ["// Generated by wordlist/build_words_da.py from wordlist/da/Y1.txt to Y6.txt. Do not edit by hand.",
             "// Danish spelling words (user's request, 2026-10-29): one group per level, Y1 (0. klasse) to Y6 (5. klasse).",
             "// Each word: [word, meaning, example sentence, why it's tricky]", "const WORD_GROUPS_DA = ["]
    for g in groups:
        lines.append(f'{{ "group": {g["group"]}, "level": "{g["level"]}", "words": [')
        lines += [json.dumps(w, ensure_ascii=False) + "," for w in g["words"]]
        lines.append("] },")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.name}: " + ", ".join(f"Y{g['group']} {len(g['words'])}" for g in groups) + f", {sum(len(g['words']) for g in groups)} words")


if __name__ == "__main__":
    main()
